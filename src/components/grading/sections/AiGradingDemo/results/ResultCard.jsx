import React, { useMemo } from "react";
import { motion } from "framer-motion";
import {
  Scale,
  Ruler,
  Sparkles,
  ShieldCheck,
} from "lucide-react";

import GradeBadge from "./GradeBadge";
import MetricCard from "./MetricCard";
import ConfidenceRing from "./ConfidenceRing";
import PriceCard from "./PriceCard";
import FeatureList from "./FeatureList";

import calculateRecommendedPrice
  from "../../../pricing/PricingEngine";

import {
  getMarketData,
  getTrendLabel,
} from "../../../pricing/MarketData";


const ResultCard = ({

  // ========================================================
  // AI GRADING RESULT
  // ========================================================

  grade = "A",

  confidence = 98,


  // ========================================================
  // PRODUCE
  // ========================================================

  produce = "tomatoes",


  // ========================================================
  // PRODUCE METRICS
  // ========================================================

  metrics = {
    weight: "10.2",
    size: "48",
    freshness: "96",
    defects: "2",
  },


  // ========================================================
  // AI DETECTED FEATURES
  // ========================================================

  features = [
    "Large Size",
    "Smooth Surface",
    "Fresh Appearance",
    "Uniform Shape",
    "No Visible Defects",
    "Premium Market Quality",
  ],

}) => {


  // ========================================================
  // FARM-GATE MARKET DATA
  // ========================================================

  const marketData = useMemo(() => {

    return getMarketData(produce);

  }, [produce]);


  // ========================================================
  // FARM-GATE OFFER PRICE
  // ========================================================

  const farmGateOffer = useMemo(() => {

    return calculateRecommendedPrice({

      basePrice:
        marketData.basePrice,

      grade,

      marketTrend:
        marketData.marketTrend,

      seasonalDemand:
        marketData.seasonalDemand,

    });

  }, [
    marketData,
    grade,
  ]);


  // ========================================================
  // MARKET TREND LABEL
  // ========================================================

  const marketTrendLabel =
    getTrendLabel(
      marketData.marketTrend
    );


  return (

    <motion.section

      initial={{
        opacity: 0,
        y: 30,
      }}

      whileInView={{
        opacity: 1,
        y: 0,
      }}

      viewport={{
        once: true,
      }}

      transition={{
        duration: 0.6,
      }}

      className="
        w-full
        rounded-[2rem]
        bg-slate-50
        border
        border-gray-200
        p-5
        sm:p-6
        lg:p-8
      "
    >


      {/* ====================================================
          HEADER
      ===================================================== */}

      <div
        className="
          flex
          flex-col
          sm:flex-row
          sm:items-center
          sm:justify-between
          gap-4
        "
      >

        <div>

          <div className="flex items-center gap-2">

            <ShieldCheck
              size={22}
              className="text-primary"
            />

            <span
              className="
                text-sm
                font-bold
                uppercase
                tracking-wider
                text-primary
              "
            >
              AI Assessment
            </span>

          </div>


          <h2
            className="
              mt-2
              text-2xl
              lg:text-3xl
              font-black
              text-slate-900
            "
          >
            Produce Analysis Result
          </h2>


          <p
            className="
              mt-2
              text-sm
              lg:text-base
              text-gray-500
            "
          >
            Standardized quality assessment generated by
            AgriFlow AI.
          </p>

        </div>


        {/* Status */}

        <div
          className="
            self-start
            sm:self-auto
            inline-flex
            items-center
            gap-2
            rounded-full
            bg-green-100
            px-4
            py-2
            text-sm
            font-semibold
            text-primary
          "
        >

          <span
            className="
              w-2
              h-2
              rounded-full
              bg-primary
              animate-pulse
            "
          />

          Analysis Complete

        </div>

      </div>



      {/* ====================================================
          GRADE + CONFIDENCE
      ===================================================== */}

      <div
        className="
          mt-8
          grid
          grid-cols-1
          md:grid-cols-2
          gap-6
          items-stretch
        "
      >

        <div
          className="
            rounded-3xl
            bg-white
            border
            border-gray-200
            shadow-sm
            p-6
            flex
            items-center
            justify-center
          "
        >

          <GradeBadge
            grade={grade}
            confidence={confidence}
          />

        </div>


        <div>

          <ConfidenceRing
            percentage={confidence}
          />

        </div>

      </div>



      {/* ====================================================
          METRICS
      ===================================================== */}

      <div className="mt-8">

        <div className="flex items-center gap-2 mb-4">

          <Sparkles
            size={20}
            className="text-primary"
          />

          <h3
            className="
              text-lg
              font-bold
              text-slate-900
            "
          >
            Produce Metrics
          </h3>

        </div>


        <div
          className="
            grid
            grid-cols-2
            lg:grid-cols-4
            gap-4
          "
        >

          <MetricCard
            icon={Scale}
            title="Average Weight"
            value={metrics.weight}
            unit="kg"
            color="green"
          />

          <MetricCard
            icon={Ruler}
            title="Estimated Size"
            value={metrics.size}
            unit="cm"
            color="blue"
          />

          <MetricCard
            icon={Sparkles}
            title="Freshness"
            value={metrics.freshness}
            unit="%"
            color="green"
          />

          <MetricCard
            icon={ShieldCheck}
            title="Defect Score"
            value={metrics.defects}
            unit="%"
            color="orange"
          />

        </div>

      </div>



      {/* ====================================================
          FEATURES
      ===================================================== */}

      <div className="mt-8">

        <FeatureList
          features={features}
        />

      </div>



      {/* ====================================================
          FARM-GATE PRICE OFFER
      ===================================================== */}

      <div className="mt-8">

        <PriceCard

          price={farmGateOffer}

          grade={grade}

          produce={marketData.produce}

          market={marketData.market}

          location={marketData.location}

          currency={marketData.currency}

          marketTrend={
            marketData.marketTrend
          }

          marketTrendLabel={
            marketTrendLabel
          }

          seasonalDemand={
            marketData.seasonalDemand
          }

        />

      </div>



      {/* ====================================================
          FOOTNOTE
      ===================================================== */}

      <div
        className="
          mt-6
          flex
          items-start
          gap-3
          rounded-2xl
          bg-white
          border
          border-gray-200
          p-4
        "
      >

        <ShieldCheck
          size={20}
          className="
            shrink-0
            mt-0.5
            text-primary
          "
        />


        <p
          className="
            text-xs
            sm:text-sm
            leading-6
            text-gray-500
          "
        >
          This farm-gate offer is generated from the
          produce quality assessment and current
          farm-gate market conditions. It represents
          an estimated price AgriFlow AI could offer
          the farmer.

          Final offers may vary based on actual market
          conditions, produce availability and
          transaction location.

        </p>

      </div>

    </motion.section>

  );

};


export default ResultCard;